function Button({
  className,
  disabled,
  href,
  onClick,
  variant = "default",
  size = "default",
  ...props
}) {
  const buttonClassName = cn(buttonVariants({ variant, size, className }));
  if (href) {
    return (
      <a
        aria-disabled={disabled || undefined}
        data-slot="button"
        href={href}
        tabIndex={disabled ? -1 : undefined}
        className={buttonClassName}
        onClick={event => {
          if (disabled) {
            event.preventDefault();
            return;
          }
          onClick?.(event);
        }}
        {...props}
      />
    );
  }

  return (
    <ButtonPrimitive
      data-slot="button"
      disabled={disabled}
      className={buttonClassName}
      onClick={onClick}
      {...props} />
  );
}

export { Button, buttonVariants }
